function asStrings(value) {
  if (Array.isArray(value)) return value.filter((item) => typeof item === "string");
  if (typeof value !== "string" || !value.trim()) return [];
  const source = value.trim();
  if (source.startsWith("[")) {
    try {
      const parsed = JSON.parse(source);
      if (Array.isArray(parsed)) return parsed.filter((item) => typeof item === "string");
    } catch {}
  }
  return source.split(/[,،;؛|\n\r]+/u);
}

function cleanUnique(values, limit) {
  const result = [];
  const seen = new Set();
  for (const raw of values) {
    const value = raw.replace(/\s+/gu, " ").trim().replace(/^[,،;؛|]+|[,،;؛|]+$/gu, "");
    if (!value) continue;
    const key = value.normalize("NFKC").replace(/[\u064B-\u065F\u0670]/gu, "").toLocaleLowerCase("ar");
    if (/(?:^|[\s|،])(?:(?:مؤسسة|شركة)\s+)?(?:السهم\s+كلين|سبائك\s+الماسة)(?=$|[\s|،])/u.test(key)
      || key.includes("منصة باقات التنظيف")) continue;
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(value);
    if (result.length >= limit) break;
  }
  return result;
}

function normalizeKeywords(value, primary = "") {
  return cleanUnique([primary, ...asStrings(value)], 8).join("، ");
}

function normalizeTags(value, primary = "") {
  return JSON.stringify(cleanUnique([primary, ...asStrings(value)], 5));
}

function escapeHtml(value) {
  return value.replace(/&/gu, "&amp;").replace(/</gu, "&lt;").replace(/>/gu, "&gt;");
}

