const updatePage = db.prepare(`
  UPDATE seo_pages
  SET seo_keywords = ?, tags = ?, content = ?, updated_at = datetime('now')
  WHERE id = ?
`);
const updatePost = db.prepare(`
  UPDATE posts SET seo_keywords = ?, tags = ?, updated_at = datetime('now')
  WHERE id = ?
`);
const updateService = db.prepare("UPDATE services SET seo_keywords = ? WHERE id = ?");
const updatePackage = db.prepare("UPDATE packages SET seo_keywords = ? WHERE id = ?");

const transaction = db.transaction(() => {
  let keywordChanges = 0;
  let tagChanges = 0;
  let contentChanges = 0;
  let contentSpecsValidated = 0;
  const pages = db.prepare("SELECT id, slug, title, target_keyword, seo_keywords, tags, content FROM seo_pages").all();
  for (const page of pages) {
    const primary = page.target_keyword || page.title || "";
    const keywords = normalizeKeywords(page.seo_keywords, primary);
    const tags = normalizeTags(page.tags, primary);
    const contentSpec = pageContent.find((item) => item.id === page.id);
    const content = contentSpec ? renderPageContent(contentSpec) : page.content;
    if (contentSpec && contentSpec.slug !== page.slug) {
      throw new Error(`SEO content target changed unexpectedly for page id ${page.id}`);
    }
    if (contentSpec) {
      contentSpecsValidated++;
      if (!getSeoPageIndexability({ ...page, content }).indexable) {
        throw new Error(`SEO page id ${page.id} did not pass the content indexability policy`);
      }
      if (content.replace(/<[^>]*>/gu, " ").replace(/\s+/gu, " ").trim().length < 900) {
        throw new Error(`SEO page id ${page.id} has less than 900 visible content characters`);
      }
    }
    const keywordChanged = keywords !== (page.seo_keywords || "");
    const tagChanged = tags !== (page.tags || "[]");
    const contentChanged = Boolean(contentSpec && content !== page.content);
    if (keywordChanged || tagChanged || contentChanged) {
      updatePage.run(keywords, tags, content, page.id);
      if (keywordChanged) keywordChanges++;
      if (tagChanged) tagChanges++;
      if (contentChanged) contentChanges++;
    }
  }

  for (const post of db.prepare("SELECT id, title, seo_keywords, tags FROM posts").all()) {
    const primary = normalizeKeywords(post.seo_keywords).split("، ")[0] || post.title || "";
    const keywords = normalizeKeywords(post.seo_keywords, primary);
    const tags = normalizeTags(post.tags, primary);
    if (keywords !== (post.seo_keywords || "") || tags !== (post.tags || "[]")) {
      updatePost.run(keywords, tags, post.id);
      if (keywords !== (post.seo_keywords || "")) keywordChanges++;
      if (tags !== (post.tags || "[]")) tagChanges++;
    }
  }

  for (const service of db.prepare("SELECT id, title, seo_keywords FROM services").all()) {
    const primary = normalizeKeywords(service.seo_keywords).split("، ")[0] || service.title || "";
    const keywords = normalizeKeywords(service.seo_keywords, primary);
    if (keywords !== (service.seo_keywords || "")) {
      updateService.run(keywords, service.id);
      keywordChanges++;
    }
  }

  for (const item of db.prepare("SELECT id, name, seo_keywords FROM packages").all()) {
    const primary = normalizeKeywords(item.seo_keywords).split("، ")[0] || item.name || "";
    const keywords = normalizeKeywords(item.seo_keywords, primary);
    if (keywords !== (item.seo_keywords || "")) {
      updatePackage.run(keywords, item.id);
      keywordChanges++;
    }
  }

  if (contentSpecsValidated !== pageContent.length) {
    throw new Error(`Expected ${pageContent.length} validated page content specs; got ${contentSpecsValidated}`);
  }
  return { keywordChanges, tagChanges, contentChanges, contentSpecsValidated };
});

